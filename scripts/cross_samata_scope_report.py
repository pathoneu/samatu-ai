"""Cross-sąmata scope-pattern report — Rangovas A N=6.

Builds a metric × project matrix showing which categories each project
prices, which it omits, and the per-metric value spread across the 6
contractor sąmatas. Output goes to docs/scope_pattern_report.md.

Zero Vision spend; reads truth.json files only.

What this is FOR:
  • Reveal scope conventions the calibration_learner will need to absorb
  • Surface metrics that are missing from some sąmatas but present in others
  • Guard against false promotion candidates by quantifying per-metric
    coverage (a metric present in only 2/6 projects can't be globally
    promoted)
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]


def _load_all() -> list[dict]:
    reg = yaml.safe_load((REPO_ROOT / "ground_truth/registry.yaml").read_text())
    out = []
    for entry in reg.get("projects") or []:
        truth = json.loads((REPO_ROOT / entry["truth_path"]).read_text())
        out.append({
            "slug": entry["slug"], "name": entry.get("name", entry["slug"]),
            "truth": truth, "contractor": entry.get("contractor", "?"),
        })
    return out


def _value(metric_body) -> float | None:
    if not isinstance(metric_body, dict):
        return None
    v = metric_body.get("value")
    if isinstance(v, list):
        return sum(float(x) for x in v if isinstance(x, (int, float)))
    return float(v) if isinstance(v, (int, float)) else None


def main() -> int:
    projects = _load_all()
    slugs = [p["slug"] for p in projects]

    # Collect every metric key across projects
    all_metrics: set[str] = set()
    for p in projects:
        all_metrics |= (p["truth"].get("gt_totals") or {}).keys()

    # Build matrix
    matrix: dict[str, dict[str, float | None]] = {}
    for m in sorted(all_metrics):
        matrix[m] = {}
        for p in projects:
            body = (p["truth"].get("gt_totals") or {}).get(m)
            matrix[m][p["slug"]] = _value(body) if body else None

    # Per-metric coverage stats
    rows = []
    for m, values in matrix.items():
        present = [v for v in values.values() if v is not None]
        rows.append({
            "metric": m,
            "n_present": len(present),
            "n_total": len(slugs),
            "min": min(present) if present else None,
            "max": max(present) if present else None,
            "median": statistics.median(present) if present else None,
        })

    # Render markdown
    lines = []
    lines.append("# Cross-sąmata scope pattern — Rangovas A N=6\n")
    lines.append("Auto-generated by `scripts/cross_samata_scope_report.py`. "
                 "Zero Vision spend.\n")
    lines.append("## Critical caveat: single contractor\n")
    lines.append("All 6 sąmatos are by **Rangovas A**. ")
    lines.append("Calibration patterns observed here are rangovas's scope conventions, ")
    lines.append("**not** Lithuanian industry averages. Cross-contractor calibration ")
    lines.append("needs ≥1 non-Rangovas A truth file before the calibration_learner's ")
    lines.append("promotion gate has industry-wide signal.\n")
    lines.append("## Per-metric coverage\n")
    lines.append("| Metric | Present | Min | Median | Max | Spread |")
    lines.append("|---|---:|---:|---:|---:|---:|")
    for r in sorted(rows, key=lambda x: -x["n_present"]):
        if r["n_present"] == 0:
            continue
        spread_pct = ((r["max"] - r["min"]) / r["median"] * 100) if r["median"] else None
        spread_s = f"{spread_pct:.0f}%" if spread_pct is not None else "—"
        lines.append(f"| `{r['metric']}` | {r['n_present']}/{r['n_total']} | "
                     f"{r['min']:.2f} | {r['median']:.2f} | {r['max']:.2f} | {spread_s} |")

    lines.append("\n## Project × Metric matrix\n")
    # Pivot: rows=metric, columns=project slug
    header_cells = ["metric"] + slugs
    lines.append("| " + " | ".join(header_cells) + " |")
    lines.append("|" + "---|" * (len(slugs) + 1))
    for m, values in matrix.items():
        cells = [f"`{m}`"]
        for s in slugs:
            v = values.get(s)
            cells.append("—" if v is None else f"{v:.2f}")
        lines.append("| " + " | ".join(cells) + " |")

    # Universal-coverage metrics (present in 6/6)
    universal = [r for r in rows if r["n_present"] == len(slugs)]
    if universal:
        lines.append(f"\n## Universal metrics (6/6 projects)\n")
        lines.append("These can become calibration_learner promotion candidates "
                     "if direction-consistency holds:\n")
        for r in universal:
            lines.append(f"- `{r['metric']}` — median {r['median']:.2f} "
                         f"({r['n_total']}/{r['n_total']} coverage)")

    # Sparse metrics (present in <50%)
    sparse = [r for r in rows
              if 0 < r["n_present"] < len(slugs) // 2 + 1]
    if sparse:
        lines.append(f"\n## Sparse metrics (<50% coverage)\n")
        lines.append("Project-specific scope items. Don't expect these to "
                     "yield global promotion candidates:\n")
        for r in sparse:
            lines.append(f"- `{r['metric']}` — {r['n_present']}/{r['n_total']} projects")

    # Direct observations across all 6
    lines.append("\n## Observations\n")
    obs = []
    # Combined paint metric coverage
    combined = matrix.get("dazymo_walls_plus_ceilings_combined_m2", {})
    n_with_combined = sum(1 for v in combined.values() if v is not None)
    obs.append(f"- **Combined paint** (`dazymo_walls_plus_ceilings_combined_m2`) is present "
               f"in {n_with_combined}/6 projects — the strongest cross-project headline metric.")
    if n_with_combined >= 3:
        present_vals = [v for v in combined.values() if v is not None]
        obs.append(f"  Values range {min(present_vals):.0f}–{max(present_vals):.0f} m² "
                   f"(median {statistics.median(present_vals):.0f}); the spread reflects "
                   f"project size, not error.")

    # Angokraščiai coverage
    angok = matrix.get("angokrasciu_m", {})
    n_angok = sum(1 for v in angok.values() if v is not None)
    obs.append(f"- **Angokraščiai** (`angokrasciu_m`) present in {n_angok}/6. Rangovas uses "
               f"two distinct line items in some projects: 'Angokraščių apdirbimas GKP' "
               f"AND 'Durų angų paruošimas' — these aren't always merged (see Objektas B "
               f"and Lazūnų).")

    # LED coverage
    led = matrix.get("led_nisos_m", {})
    n_led = sum(1 for v in led.values() if v is not None)
    obs.append(f"- **LED nišos** present in {n_led}/6. Two projects (`sernu`, `romainiai` only "
               f"profiliai) don't have a Nišų-formavimas line — interior style varies.")

    # GKP virš 3m
    gkp_virs = matrix.get("gkp_lubu_virs_3m_m2", {})
    n_gkp_virs = sum(1 for v in gkp_virs.values() if v is not None)
    obs.append(f"- **GKP virš 3m** present in only {n_gkp_virs}/6 — most projects are "
               f"single-tier ceilings. The virš-3m split is a feature of larger houses, "
               f"not a universal metric.")

    # Plytelės
    plyt = matrix.get("plyteles_sienos_grindys_combined_m2", {})
    n_plyt = sum(1 for v in plyt.values() if v is not None)
    obs.append(f"- **Plytelės sienos+grindys combined** present in {n_plyt}/6 — three projects "
               f"use this combined unit, Beržų splits into separate sienos and grindys, "
               f"romainiai has no tile work at all.")

    for o in obs:
        lines.append(o)

    lines.append("\n## What this means for the calibration_learner\n")
    lines.append(
        "Of ~30 metrics in the matrix, only **2-3 are present in ≥4/6 projects**: "
        "`dazymo_walls_plus_ceilings_combined_m2`, `kampu_metrai_m`, `angokrasciu_m`. "
        "Even these are single-contractor — calibration_learner.PROMOTION_RULES "
        "should remain at `min_projects=3` AND require non-Rangovas A data before any "
        "factor is promoted to `formulas.yaml`. The current gates "
        "(IQR≤0.05, 100% direction consistency, |median - 1| > 0.005) are the right "
        "guardrails; the data simply doesn't yet pass them.\n"
    )

    out = REPO_ROOT / "docs/scope_pattern_report.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"  Report → {out.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
