"""Retire detector pipelines P3-P6 (Week 8 Task 8.2 — D8).

Why: AI-seeded ground truth in the original bake-off was Claude grading
Claude. The ranking that "won" P1 over P3-P6 is invalid because the GT
was generated by the same model family. Three of the four (P3 cv2 over-
counting 100×, P4 hybrid implementation-broken, P5 GroundingDINO ran out
of credit) were also empirically unreliable. P6 Claude tool-orch was
23% accuracy at 12× the cost of P1. Retiring all four removes maintenance
burden + JSON noise from runs against the new human GT.

P2 (pdfplumber regex) is KEPT as a zero-cost regression baseline — it
runs free, gives "are we still beating baseline?" sanity, and our R6
research said: don't throw away a free signal.

Usage:
  python scripts/retire_detector_pipelines.py --dry-run
  python scripts/retire_detector_pipelines.py
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

REPO_ROOT = Path(__file__).resolve().parents[1]
DETECTORS_DIR = REPO_ROOT / "detector_bench" / "detectors"

DEFAULT_RETIRE = ["P3", "P4", "P5", "P6"]


def find_detector_files(pipeline: str) -> list[Path]:
    """Locate the detector module(s) for a pipeline ID like 'P3'."""
    p = pipeline.lower()
    return sorted(DETECTORS_DIR.glob(f"{p}_*.py"))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--retire", nargs="+", default=DEFAULT_RETIRE)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if not DETECTORS_DIR.exists():
        print(f"WARN: {DETECTORS_DIR} not found; nothing to retire.")
        return 0

    total = 0
    for pipeline in args.retire:
        files = find_detector_files(pipeline)
        if not files:
            print(f"  {pipeline}: no files found")
            continue
        for f in files:
            verb = "would delete" if args.dry_run else "deleting"
            print(f"  {verb} {f.relative_to(REPO_ROOT)}")
            if not args.dry_run:
                f.unlink()
            total += 1
    print(
        f"\n{'Would retire' if args.dry_run else 'Retired'} "
        f"{total} detector module(s). P1 + P2 remain active."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
